function specFor(asin) {
  const s = SPECS[asin] || {};
  const set2 = !!s.set2;
  return {
    noun: s.noun || '地毯',
    geometry:
      s.geometry ||
      (set2
        ? (s.diag ? SET2_DIAG : SET2_VERT).replace('{{RATIO}}', s.ratio || '见参考图')
        : RECT_VERT.replace('{{RATIO}}', s.ratio || '见参考图')),
    pattern: s.pattern || '以参考图中的实际花色为准，逐区域忠实还原',
    refNote: s.refNote || '',
    only: set2 ? '这两块同款' + (s.noun || '地毯') : '这一个' + (s.noun || '地毯'),
  };
}

function promptFor(asin) {
  const s = specFor(asin);
  return COMMON.replace(/\{\{NOUN\}\}/g, s.noun)
    .replace('{{GEOMETRY}}', s.geometry)
    .replace('{{PATTERN}}', s.pattern)
    .replace('{{REF_NOTE}}', s.refNote || '')
    .replace('{{ONLY}}', s.only);
}

async function dataUri(file) {
  const sharp = require('sharp');
  const buf = await sharp(file).resize(1024, 1024, { fit: 'inside' }).jpeg({ quality: 85 }).toBuffer();
  return `data:image/jpeg;base64,${buf.toString('base64')}`;
}

